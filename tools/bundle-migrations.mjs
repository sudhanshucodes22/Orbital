#!/usr/bin/env node
/** Concatenates the migrations into one file for a single paste.
 *
 *   npm run migrations:bundle
 *
 * ## Why the output is not wrapped in a transaction
 *
 * It was, once, and that was a mistake worth recording. Every migration here is
 * individually idempotent — `if not exists`, `drop ... if exists` before
 * create — precisely so that applying half of them is safe and re-running
 * resumes from where it stopped. Wrapping the lot in `begin/commit` throws that
 * property away: one failing statement rolls back all seven, turning "six
 * applied, fix one thing" into "nothing applied, and the editor's error is
 * about a statement in the middle of a 700-line file".
 *
 * That is not hypothetical. The first live attempt failed exactly this way:
 * the whole bundle rolled back, and the absence of the storage bucket — which
 * comes from the second migration — is what proved the rollback rather than a
 * stale schema cache.
 *
 * Atomicity is the right instinct for a migration that must not be half-applied.
 * It is the wrong instinct for a set that was designed to be resumable.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const DIR = join(process.cwd(), "supabase", "migrations");
const OUT = join(process.cwd(), "supabase", "ALL_MIGRATIONS.sql");

const files = readdirSync(DIR)
  .filter((f) => f.endsWith(".sql"))
  .sort();

if (files.length === 0) {
  console.error("  No migrations found in supabase/migrations.");
  process.exit(1);
}

const header = `-- Orbital — all migrations, concatenated for a single paste.
--
-- Generated by \`npm run migrations:bundle\`. Do not edit; edit the individual
-- migrations and regenerate.
--
-- Run this in the Supabase SQL Editor.
--
-- DELIBERATELY NOT WRAPPED IN A TRANSACTION. Every statement is idempotent, so
-- partial application is safe and re-running resumes where it stopped. A
-- transaction would turn "six of seven applied" into "nothing applied" — which
-- is exactly what happened on the first attempt here: one statement failed and
-- silently discarded the other six, including the storage bucket.
--
-- If a statement fails, the editor names it. Everything before it has
-- persisted; fix that one thing and run the file again.
--
-- Note: 0001 creates a trigger on auth.users so a personal workspace is made
-- at signup. That needs ownership of auth.users, which the SQL Editor has and
-- most other connections do not. If it is the statement that fails, run this
-- file from the SQL Editor specifically.
--
-- Files, in order:
${files.map((f) => `--   ${f}`).join("\n")}
`;

const body = files
  .map(
    (f) =>
      `\n-- ${"=".repeat(74)}\n-- ${f}\n-- ${"=".repeat(74)}\n\n` +
      `${readFileSync(join(DIR, f), "utf8").trim()}\n`
  )
  .join("");

/** A closing report, so the outcome is visible rather than inferred. */
const footer = `
-- ${"=".repeat(74)}
-- Did it work?
-- ${"=".repeat(74)}
--
-- Expect seven rows: six tables plus the storage bucket. Anything missing is a
-- statement that failed above.

select 'table: ' || table_name as applied
  from information_schema.tables
 where table_schema = 'public'
   and table_name in ('workspaces','workspace_members','projects',
                      'project_files','project_revisions','generation_runs')
union all
select 'bucket: ' || id from storage.buckets where id = 'orbital-artifacts'
 order by applied;
`;

writeFileSync(OUT, header + body + footer);
console.log(`  bundled ${files.length} migrations → supabase/ALL_MIGRATIONS.sql`);
console.log("  no transaction wrapper: a failure keeps what already applied");
